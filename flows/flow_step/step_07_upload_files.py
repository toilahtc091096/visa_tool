def _named_slot_files(folder: str, names: list[str]) -> list[Path | None]:
    """One file per slot, in ``names`` order: the file with that name (any
    extension and case), else the next other file of the folder (by name).
    None keeps an empty slot so later files stay in their own slot."""
    files = sorted(get_files(folder, 1000), key=lambda f: f.name.lower())
    by_stem: dict[str, Path] = {}
    for f in files:
        by_stem.setdefault(f.stem.lower(), f)
    wanted = {name.lower() for name in names}
    rest = [f for f in files if f.stem.lower() not in wanted]
    slots: list[Path | None] = []
    for name in names:
        f = by_stem.get(name.lower())
        if f is None and rest:
            f = rest.pop(0)
        slots.append(f)
    return slots


def _qcm_slot_files(folder: str) -> list[Path | None]:
    """North Q1 / Q2 relationship proof (4 slots: _1 optional, _2 _3 _4 required
    on COVA), from the number of files (by name):
    4+ -> _1.._4; 3 -> _2 _3 _4 (_1 empty); 2 -> _2 _3 _4 with the first file
    again in _4; 1 -> the same file in _2 _3 _4. None keeps _1 empty."""
    files = sorted(get_files(folder, 1000), key=lambda f: f.name.lower())
    if len(files) >= 4:
        return files[:4]
    if len(files) == 3:
        return [None, *files]
    if len(files) == 2:
        return [None, files[0], files[1], files[0]]
    if len(files) == 1:
        return [None, files[0], files[0], files[0]]
    return []


def _source_files(cfg: dict | list, data_passport_number: str) -> list[Path]:
    if isinstance(cfg, list):
        return [f for source in cfg for f in _source_files(source, data_passport_number)]
    if "first_of" in cfg:
        for source in cfg["first_of"]:
            files = _source_files(source, data_passport_number)
            if files:
                return files
        return []
    if "merge_pdf" in cfg:
        files = [f for source in cfg["merge_pdf"] for f in _source_files(source, data_passport_number)]
        merged = merge_files_to_pdf(files, cfg["name"]) if files else None
        return [merged] if merged else []
    if "named_slots" in cfg:
        return _named_slot_files(cfg["folder"], cfg["named_slots"])
    if cfg.get("qcm_slots"):
        return _qcm_slot_files(cfg["folder"])
    if cfg.get("passport_image"):
        path = get_passport_file_path(PASSPORT_FILE_FOLDER, prefix=data_passport_number)
        return [Path(path)] if path else []
    if cfg.get("sort") == "name_desc":
        files = get_files(
            cfg["folder"],
            1000,
            cfg.get("prefix", ""),
            cfg.get("exclude", ()),
            cfg.get("names", ()),
        )
        files.sort(key=lambda f: f.name.lower(), reverse=True)
        return files[: cfg["limit"]]
    return get_files(
        cfg["folder"],
        cfg["limit"],
        cfg.get("prefix", ""),
        cfg.get("exclude", ()),
        cfg.get("names", ()),
    )


async def upload_files(
    ctx,
    client,
    is_update_info: bool = False,
    upload_config_keys=None,
) -> bool:
    ctx.step = "Step 9 Upload File"
    data_passport_number = getattr(ctx, "input_passportNumber", ctx.passportNumber)
    ensure_data_folder_downloaded(data_passport_number)
    ctx.profile.prepare_resources(ctx)
    selected_upload_keys = set(upload_config_keys or [])
    # Calling /run again reuses the same draft application. Without a family
    # passport every file is generated by this run, so clear each slot first:
    # COVA must never keep a file (e.g. a flight ticket) from an earlier run.
    replace_existing = not str(getattr(ctx, "family_passport", "") or "").strip()

    for item in ctx.profile.upload_plan():
        all_upload_files = [
            f
            for cfg in item.configs
            for f in _source_files(cfg, data_passport_number)
        ]
        for f_doc, upload_file in zip(item.codes, all_upload_files):
            if not upload_file:
                continue
            if replace_existing:
                ctx.step = (
                    f"remove_upload_file {item.doc_type} "
                    f"{f_doc['categoryCode']}/{f_doc['materialCode']}"
                )
                ok_remove, meta_remove = await api_remove_upload_file(
                    client,
                    ctx.token,
                    ctx.tmp_secret,
                    f_doc["categoryCode"],
                    f_doc["materialCode"],
                    ctx.first_applyid,
                )
                log_event({"step": ctx.step, "ok": ok_remove, **meta_remove})
                # Only HTTP failures stop the flow: removing an empty slot is
                # expected to come back as a business error.
                if not ok_remove:
                    return await fail_step(
                        ctx,
                        meta_remove.get("error") or "request failed",
                        status_code=meta_remove.get("status_code"),
                        response=meta_remove.get("response"),
                    )
            ctx.step = (
                f"upload_file {item.doc_type} "
                f"{f_doc['categoryCode']}/{f_doc['materialCode']} {upload_file.name}"
            )
            ok, meta = await api_upload_file_common(
                client,
                ctx.token,
                ctx.tmp_secret,
                upload_file,
                f_doc["categoryCode"],
                f_doc["materialCode"],
                ctx.first_applyid,
            )
            if not await check_api_result(ctx, ok, meta):
                return False
    return True
